export const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, id };

export function translate(lang: Language, key: TranslationKey) {
  return dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
}

/** Countdown label for a bill due date, localised. */
export function dueLabelFor(lang: Language, days: number) {
  if (Number.isNaN(days)) return null;
  const unit = translate(lang, Math.abs(days) === 1 ? "common.day" : "common.days");
  if (days < 0) return `${translate(lang, "common.overdueBy")} ${Math.abs(days)} ${unit}`;
  if (days === 0) return translate(lang, "common.dueToday");
  if (days === 1) return translate(lang, "common.dueTomorrow");
  return `${translate(lang, "common.dueIn")} ${days} ${unit}`;
}

/** Hook returning the translator bound to the user's current language. */
export function useT() {
  const { settings } = useFinance();
  const lang = settings.language;
  const t = (key: TranslationKey) => translate(lang, key);
  return { t, lang };
}
